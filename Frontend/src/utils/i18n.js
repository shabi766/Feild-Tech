// Format currency
export const formatCurrency = (amount, currency = 'USD', language = 'en') => {
  const formatter = new Intl.NumberFormat(language === 'en' ? 'en-US' : language, {
    style: 'currency',
    currency: currency,
    minimumFractionDigits: 2
  });
  return formatter.format(amount);
};

// Format date
export const formatDate = (date, format = 'MM/DD/YYYY', language = 'en') => {
  const d = new Date(date);
  const options = { 
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  };
  
  return d.toLocaleDateString(language, options);
};

// Format time
export const formatTime = (date, format = '12h', language = 'en') => {
  const d = new Date(date);
  const options = { 
    hour: 'numeric',
    minute: '2-digit',
    hour12: format === '12h'
  };
  
  return d.toLocaleTimeString(language, options);
};
